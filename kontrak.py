from abc import ABC, abstractmethod

class RepositoriBuku(ABC):
    @abstractmethod
    def simpan(self, buku): ...
    @abstractmethod
    def cari_isbn(self, isbn): ...
    @abstractmethod
    def semua(self): ...

class RepositoriAnggota(ABC):
    @abstractmethod
    def simpan(self, anggota): ...
    @abstractmethod
    def cari_id(self, id_anggota): ...
    @abstractmethod
    def semua(self): ...

class RepositoriTransaksi(ABC):
    @abstractmethod
    def simpan(self, transaksi): ...
    @abstractmethod
    def cari_id(self, id_transaksi): ...
    @abstractmethod
    def semua(self): ...
